function AccordionSection({ section }: { section: Section }) {
  const [open, setOpen] = useState(false)
  return (
    <div className="rounded-xl border border-[#E5E5E5] overflow-hidden">
      <button
        onClick={() => setOpen(o => !o)}
        className="w-full flex items-center gap-3 p-4 text-right hover:bg-[#FAFAFA] transition-colors"
      >
        <div className={`flex h-9 w-9 items-center justify-center rounded-xl flex-shrink-0 ${section.bg} ${section.color}`}>
          {section.icon}
        </div>
        <span className="flex-1 text-sm font-bold text-[#0A0A0A]">{section.title}</span>
        {open
          ? <ChevronUp className="h-4 w-4 text-[#A3A3A3]" />
          : <ChevronDown className="h-4 w-4 text-[#A3A3A3]" />
        }
      </button>
      {open && (
        <div className="px-4 pb-4 flex flex-col gap-3 border-t border-[#F0F0F0] pt-3">
          {section.steps.map((step, i) => (
            <div key={i} className="flex gap-3">
              <div className={`flex h-6 w-6 items-center justify-center rounded-full text-[11px] font-black flex-shrink-0 mt-0.5 ${section.bg} ${section.color}`}>
                {i + 1}
              </div>
              <div>
                <p className="text-sm font-bold text-[#0A0A0A]">{step.title}</p>
                <p className="text-sm text-[#737373] mt-0.5 leading-relaxed">{step.desc}</p>
              </div>
            </div>
          ))}
        </div>
      )}
    </div>
  )
}

